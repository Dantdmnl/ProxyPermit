#!/usr/bin/env bash
set -euo pipefail

ENV_FILE="${1:-.env}"
OUT_FILE="${2:-/tmp/proxypermit.conf}"

if [[ ! -f "$ENV_FILE" ]]; then
  echo "ERROR: env file not found: $ENV_FILE" >&2
  exit 1
fi

get_env() {
  local key="$1"
  local def="${2:-}"
  local raw
  raw=$(grep -E "^${key}=" "$ENV_FILE" | tail -n1 | cut -d'=' -f2- || true)
  if [[ -z "$raw" ]]; then
    printf '%s' "$def"
  else
    printf '%s' "$raw"
  fi
}

MANAGER_PORT="$(get_env MANAGER_PORT 8080)"
VIP_ADDRESS="$(get_env VIP_ADDRESS '')"
NODE0_ADDRESS="$(get_env NODE0_ADDRESS '')"
NODE1_ADDRESS="$(get_env NODE1_ADDRESS '')"

# Optional overrides for nginx specifics
NGINX_SERVER_NAME="$(get_env NGINX_SERVER_NAME "$VIP_ADDRESS")"
NGINX_SSL_CERT="$(get_env NGINX_SSL_CERT "$(get_env MANAGER_CERT '')")"
NGINX_SSL_KEY="$(get_env NGINX_SSL_KEY "$(get_env MANAGER_KEY '')")"
GUNICORN_BIND="$(get_env GUNICORN_BIND 'unix:/run/proxypermit/gunicorn.sock')"
ENABLE_HSTS="$(get_env ENABLE_HSTS 'true')"
HSTS_MAX_AGE="$(get_env HSTS_MAX_AGE '31536000')"
HSTS_INCLUDE_SUBDOMAINS="$(get_env HSTS_INCLUDE_SUBDOMAINS 'true')"
HSTS_PRELOAD="$(get_env HSTS_PRELOAD 'false')"

if [[ -z "$NGINX_SERVER_NAME" ]]; then
  NGINX_SERVER_NAME="_"
fi

if [[ -z "$NGINX_SSL_CERT" || -z "$NGINX_SSL_KEY" ]]; then
  echo "ERROR: NGINX_SSL_CERT/NGINX_SSL_KEY (or MANAGER_CERT/MANAGER_KEY) must be set in $ENV_FILE" >&2
  exit 1
fi

if [[ "$GUNICORN_BIND" == unix:* ]]; then
  PROXY_PASS="http://$GUNICORN_BIND"
else
  PROXY_PASS="http://$GUNICORN_BIND"
fi

to_bool() {
  case "$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')" in
    true|1|yes|on) echo true ;;
    *) echo false ;;
  esac
}

HSTS_VALUE=""
if [[ "$(to_bool "$ENABLE_HSTS")" == "true" ]]; then
  HSTS_VALUE="max-age=${HSTS_MAX_AGE}"
  if [[ "$(to_bool "$HSTS_INCLUDE_SUBDOMAINS")" == "true" ]]; then
    HSTS_VALUE+="; includeSubDomains"
  fi
  if [[ "$(to_bool "$HSTS_PRELOAD")" == "true" ]]; then
    HSTS_VALUE+="; preload"
  fi
fi

REDIRECT_PORT_SUFFIX=":${MANAGER_PORT}"
if [[ "$MANAGER_PORT" == "443" ]]; then
  REDIRECT_PORT_SUFFIX=""
fi

# Build allow list, unique and non-empty
ALLOW_IPS=("127.0.0.1" "::1")
for ip in "$NODE0_ADDRESS" "$NODE1_ADDRESS"; do
  [[ -n "$ip" ]] || continue
  exists=false
  for seen in "${ALLOW_IPS[@]}"; do
    if [[ "$seen" == "$ip" ]]; then
      exists=true
      break
    fi
  done
  if [[ "$exists" == false ]]; then
    ALLOW_IPS+=("$ip")
  fi
done

{
  echo "# Generated by scripts/render_nginx_config.sh"
  echo "server {"
  echo "    listen 80;"
  echo "    listen [::]:80;"
  echo "    server_name ${NGINX_SERVER_NAME};"
  echo "    return 301 https://\$host${REDIRECT_PORT_SUFFIX}\$request_uri;"
  echo "}"
  echo ""
  echo "server {"
  echo "    listen ${MANAGER_PORT} ssl http2;"
  echo "    listen [::]:${MANAGER_PORT} ssl http2;"
  echo "    server_name ${NGINX_SERVER_NAME};"
  echo ""
  echo "    ssl_certificate ${NGINX_SSL_CERT};"
  echo "    ssl_certificate_key ${NGINX_SSL_KEY};"
  echo ""
  echo "    ssl_session_timeout 1d;"
  echo "    ssl_session_cache shared:SSL:10m;"
  echo "    ssl_session_tickets off;"
  echo ""
  echo "    add_header X-Content-Type-Options nosniff always;"
  echo "    add_header X-Frame-Options DENY always;"
  echo "    add_header Referrer-Policy no-referrer always;"
  if [[ -n "$HSTS_VALUE" ]]; then
    echo "    add_header Strict-Transport-Security \"${HSTS_VALUE}\" always;"
  fi
  echo ""
  echo "    # UI gebruikt deze endpoint voor sync-status; laat deze door voor ingelogde webgebruikers."
  echo "    location = /api/sync/status {"
  echo "        proxy_pass ${PROXY_PASS};"
  echo "        proxy_http_version 1.1;"
  echo ""
  echo "        proxy_set_header Host \$host;"
  echo "        proxy_set_header X-Real-IP \$remote_addr;"
  echo "        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;"
  echo "        proxy_set_header X-Forwarded-Proto \$scheme;"
  echo "        proxy_set_header X-Forwarded-Host \$host;"
  echo "        proxy_set_header X-Forwarded-Port \$server_port;"
  echo ""
  echo "        proxy_read_timeout 120s;"
  echo "        proxy_send_timeout 120s;"
  echo "    }"
  echo ""
  echo "    # UI gebruikt deze endpoint voor peer-status; laat deze door voor ingelogde webgebruikers."
  echo "    location = /api/sync/peer-status {"
  echo "        proxy_pass ${PROXY_PASS};"
  echo "        proxy_http_version 1.1;"
  echo ""
  echo "        proxy_set_header Host \$host;"
  echo "        proxy_set_header X-Real-IP \$remote_addr;"
  echo "        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;"
  echo "        proxy_set_header X-Forwarded-Proto \$scheme;"
  echo "        proxy_set_header X-Forwarded-Host \$host;"
  echo "        proxy_set_header X-Forwarded-Port \$server_port;"
  echo ""
  echo "        proxy_read_timeout 120s;"
  echo "        proxy_send_timeout 120s;"
  echo "    }"
  echo ""
  echo "    # Alleen node-to-node sync endpoints IP-beperken; UI sync endpoints lopen via app-auth."
  echo "    location ~ ^/api/sync/(download|upload|info|set-conflict|clear-conflict)$$ {"
  for ip in "${ALLOW_IPS[@]}"; do
    echo "        allow ${ip};"
  done
  echo "        deny all;"
  echo ""
  echo "        proxy_pass ${PROXY_PASS};"
  echo "        proxy_http_version 1.1;"
  echo ""
  echo "        proxy_set_header Host \$host;"
  echo "        proxy_set_header X-Real-IP \$remote_addr;"
  echo "        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;"
  echo "        proxy_set_header X-Forwarded-Proto \$scheme;"
  echo "        proxy_set_header X-Forwarded-Host \$host;"
  echo "        proxy_set_header X-Forwarded-Port \$server_port;"
  echo ""
  echo "        proxy_read_timeout 120s;"
  echo "        proxy_send_timeout 120s;"
  echo "    }"
  echo ""
  echo "    location / {"
  echo "        proxy_pass ${PROXY_PASS};"
  echo "        proxy_http_version 1.1;"
  echo ""
  echo "        proxy_set_header Host \$host;"
  echo "        proxy_set_header X-Real-IP \$remote_addr;"
  echo "        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;"
  echo "        proxy_set_header X-Forwarded-Proto \$scheme;"
  echo "        proxy_set_header X-Forwarded-Host \$host;"
  echo "        proxy_set_header X-Forwarded-Port \$server_port;"
  echo ""
  echo "        proxy_read_timeout 120s;"
  echo "        proxy_send_timeout 120s;"
  echo "    }"
  echo "}"
} > "$OUT_FILE"

echo "Generated Nginx config: $OUT_FILE"
